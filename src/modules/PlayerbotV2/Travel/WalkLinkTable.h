// A link end is a graph node's own position, written with one decimal; the node it names is the nearest within this many yards.
inline constexpr float kWalkLinkMatchYards = 1.0f;

// Index of the point of `pts` (each with x, y, z) nearest to (x, y, z) and within kWalkLinkMatchYards, or -1 when there is none.
template <typename Points>
inline long MatchWalkLinkEnd(Points const& pts, float x, float y, float z)
{
    long best = -1;
    float best_d2 = kWalkLinkMatchYards * kWalkLinkMatchYards;
    for (std::size_t i = 0; i < pts.size(); ++i)
    {
        float const dx = pts[i].x - x, dy = pts[i].y - y, dz = pts[i].z - z;
        float const d2 = dx * dx + dy * dy + dz * dz;
        if (d2 <= best_d2)
        {
            best_d2 = d2;
            best = long(i);
        }
    }
    return best;
}

